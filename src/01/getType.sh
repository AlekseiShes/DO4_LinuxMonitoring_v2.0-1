#!/bin/bash

# Эта функция сообщает какой тип у переменной 
# unsigned, int, float или, в иных случаях string
# допускается ввод переменной в научной нотации
getType(){
    # Ниже если между знаками ^ и $ есть анализ строки:
    # [+-]?  необязательный но возможный один символ из перечня в квадратных скобках
    # [0-9]+ многократное (из-за знака плюс) вхождение символов из интервала 0-9
    # \.     вхождение и разделителя "."
    # (...)? не обязательное вхождение ...
    # [eE]   обязательно вхождение одно символа из списка

    if [[ $1 =~ ^[+-]?[0-9]+(\.[0-9]+)?([eE][+-]?[0-9]+(\.[0-9]+)?)?$ ]]; then
        separator=$(locale decimal_point) # узнаем что является разделителем дробной части
        Temp=${1/./$separator} # заменяем в $1 все символы "." на separator
        # Ниже если число в научной нотации делаем его в формате float
        float_val=$( echo ${Temp} | awk -F"E" 'BEGIN{OFMT="%10.10f"} {print $1 * (10 ^ $2)}')
        # Ниже из "$float_val" извлекаем целую (felisasi) и дробную (fraction) части
        IFS=$separator read -r felisasi fraction <<<"$float_val"
        # Ниже проверяем наличия в дробной части вхождений кроме нулей
        if [[ ! $fraction =~ [1-9] ]]; then
            # Ниже проверяем наличия отрицательного знака
            if [[ ! $float_val =~ [-] ]]; then
                echo "unsigned"
            else
                echo "int"
            fi
        else
            echo "float"
        fi
    else
        echo "string"
    fi
}

getType $1