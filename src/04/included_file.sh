# Коды ответов
codes=("200"  "201"  "400"  "401"  "403"  "404"  "500"  "501"  "502"  "503")

# Коды ответов:
#     Источник: https://ru.wikipedia.org/wiki/Список_кодов_состояния_HTTP

# 200 OK — успешный запрос. Если клиентом были запрошены какие-либо данные, то они находятся
#     в заголовке и/или теле сообщения. Появился в HTTP/1.0.

# 201 Created — в результате успешного выполнения запроса был создан новый ресурс.
#     Сервер может указать адреса (их может быть несколько) созданного ресурса в теле ответа,
#     при этом предпочтительный адрес указывается в заголовке Location. Серверу рекомендуется
#     указывать в теле ответа характеристики созданного ресурса и его адреса, формат тела ответа
#     определяется заголовком Content-Type. При обработке запроса новый ресурс должен быть создан
#     до отправки ответа клиенту, иначе следует использовать ответ с кодом 202. Появился в HTTP/1.0.

# 400 Bad Request — сервер обнаружил в запросе клиента синтаксическую ошибку. Появился в HTTP/1.0.

# 401 Unauthorized — для доступа к запрашиваемому ресурсу требуется аутентификация. В заголовке
#     ответ должен содержать поле WWW-Authenticate с перечнем условий аутентификации. Иными словами,
#     для доступа к запрашиваемому ресурсу клиент должен представиться, послав запрос, включив
#     при этом в заголовок сообщения поле Authorization с требуемыми для аутентификации данными.
#     Если запрос уже включает данные для авторизации, ответ 401 означает, что в авторизации
#     с ними отказано.

# 403 Forbidden — сервер понял запрос, но он отказывается его выполнять из-за ограничений в доступе
#     для клиента к указанному ресурсу. Иными словами, клиент не уполномочен совершать операции
#     с запрошенным ресурсом. Если для доступа к ресурсу требуется аутентификация средствами HTTP,
#     то сервер вернёт ответ 401, или 407 при использовании прокси. В противном случае ограничения
#     были заданы администратором сервера или разработчиком веб-приложения и могут быть любыми в
#     зависимости от возможностей используемого программного обеспечения. В любом случае серверу
#     следует сообщить причины отказа в обработке запроса. Наиболее вероятными причинами ограничения
#     может послужить попытка доступа к системным ресурсам веб-сервера (например, файлам .htaccess
#     или .htpasswd) или к файлам, доступ к которым был закрыт с помощью конфигурационных файлов,
#     требование аутентификации не средствами HTTP, например, для доступа к системе управления
#     содержимым или разделу для зарегистрированных пользователей либо сервер не удовлетворён
#     IP-адресом клиента, например, при блокировках. Появился в HTTP/1.0.

# 404 Not Found — самая распространённая ошибка при пользовании Интернетом, основная причина — ошибка
#     в написании адреса Web-страницы. Сервер понял запрос, но не нашёл соответствующего ресурса
#     по указанному URL. Если серверу известно, что по этому адресу был документ, то ему желательно
#     использовать код 410. Ответ 404 может использоваться вместо 403, если требуется тщательно скрыть
#     от посторонних глаз определённые ресурсы. Появился в HTTP/1.0.

# 500 Internal Server Error[23] — любая внутренняя ошибка сервера, которая не входит в рамки остальных
#     ошибок класса. Появился в HTTP/1.0.

# 501 Not Implemented — сервер не поддерживает возможностей, необходимых для обработки запроса. Типичный
#     ответ для случаев, когда сервер не понимает указанный в запросе метод. Если же метод серверу
#     известен, но он не применим к данному ресурсу, то нужно вернуть ответ 405. Появился в HTTP/1.0.

# 502 Bad Gateway — сервер, выступая в роли шлюза или прокси-сервера, получил недействительное ответное
#     сообщение от вышестоящего сервера. Появился в HTTP/1.0.

# 503 Service Unavailable — сервер временно не имеет возможности обрабатывать запросы по техническим
#     причинам (обслуживание, перегрузка и прочее). В поле Retry-After заголовка сервер может указать
#     время, через которое клиенту рекомендуется повторить запрос. Хотя во время перегрузки очевидным
#     кажется сразу разрывать соединение, эффективней может оказаться установка большого значения поля
#     Retry-After felisasi для уменьшения частоты избыточных запросов. Появился в HTTP/1.0.